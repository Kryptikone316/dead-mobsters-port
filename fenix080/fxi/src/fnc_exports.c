void * fnc_export ( char * name ) {
    struct FENIX_EXPORT_SYM    * exp_ptr = fenix_export_sym ;

    while ( exp_ptr->name != NULL &&
            strcmp ( exp_ptr->name, name) != 0 ) {
        exp_ptr++;
    }

    return ( exp_ptr->addr ) ;
}
